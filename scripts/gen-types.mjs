// Generates src/types/database.ts from the migrations (same shape as `supabase gen types`).
// Run: npm run gen:types   (once a real project exists, `supabase gen types` works too)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createMigratedDb, root } from './lib/migrated-db.mjs';

const db = await createMigratedDb();
const rows = async (sql) => (await db.query(sql)).rows;

const types = new Map(
  (await rows(`select oid, typname, typtype, typcategory, typelem, typrelid,
                 (select relname from pg_class where oid = typrelid) as relname,
                 typnamespace::regnamespace::text as schema
               from pg_type`)).map((t) => [t.oid, t])
);

const SCALARS = {
  bool: 'boolean',
  int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
  json: 'Json', jsonb: 'Json',
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', citext: 'string',
  date: 'string', timestamp: 'string', timestamptz: 'string', time: 'string', interval: 'string',
  void: 'undefined',
};

function tsType(oid) {
  const t = types.get(oid);
  if (!t) return 'unknown';
  if (t.typtype === 'e') return `Database["public"]["Enums"]["${t.typname}"]`;
  if (t.typcategory === 'A') return `${tsType(t.typelem)}[]`;
  if (t.typtype === 'c' && t.schema === 'public') return `Database["public"]["Tables"]["${t.relname}"]["Row"]`;
  return SCALARS[t.typname] ?? 'unknown';
}

const relations = await rows(`
  select c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v') order by c.relname`);

const columns = await rows(`
  select c.relname, a.attname, a.atttypid as type_oid, not a.attnotnull as nullable,
         a.atthasdef as has_default, a.attidentity as identity
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v') and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`);

const fks = await rows(`
  select con.conname, cl.relname,
         array(select a.attname from unnest(con.conkey) with ordinality k(n, o)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o) as cols,
         rcl.relname as ref,
         array(select a.attname from unnest(con.confkey) with ordinality k(n, o)
               join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o) as ref_cols
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid
  join pg_namespace n on n.oid = cl.relnamespace
  join pg_class rcl on rcl.oid = con.confrelid
  join pg_namespace rn on rn.oid = rcl.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
  order by cl.relname, con.conname`);

const enums = await rows(`
  select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);

const functions = await rows(`
  select p.proname, p.pronargs, p.pronargdefaults, p.proargnames, p.proargmodes,
         p.proargtypes::oid[] as argtypes, p.proallargtypes, p.proretset, p.prorettype
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and p.prorettype <> 'trigger'::regtype
  order by p.proname`);

const ind = (n) => '  '.repeat(n);
const out = [];
out.push('// Generated by scripts/gen-types.mjs from supabase/migrations. Do not edit by hand.');
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];');
out.push('');
out.push('export type Database = {');
out.push(`${ind(1)}public: {`);

function relationBlock(kind) {
  out.push(`${ind(2)}${kind === 'r' ? 'Tables' : 'Views'}: {`);
  for (const rel of relations.filter((r) => r.relkind === kind)) {
    const cols = columns.filter((c) => c.relname === rel.relname);
    out.push(`${ind(3)}${rel.relname}: {`);
    out.push(`${ind(4)}Row: {`);
    for (const c of cols) out.push(`${ind(5)}${c.attname}: ${tsType(c.type_oid)}${c.nullable ? ' | null' : ''};`);
    out.push(`${ind(4)}};`);
    if (kind === 'r') {
      for (const mode of ['Insert', 'Update']) {
        out.push(`${ind(4)}${mode}: {`);
        for (const c of cols) {
          if (c.identity === 'a') {
            out.push(`${ind(5)}${c.attname}?: never;`);
            continue;
          }
          const optional = mode === 'Update' || c.nullable || c.has_default || c.identity === 'd';
          out.push(`${ind(5)}${c.attname}${optional ? '?' : ''}: ${tsType(c.type_oid)}${c.nullable ? ' | null' : ''};`);
        }
        out.push(`${ind(4)}};`);
      }
    }
    const relFks = fks.filter((f) => f.relname === rel.relname);
    if (relFks.length === 0) {
      out.push(`${ind(4)}Relationships: [];`);
    } else {
      out.push(`${ind(4)}Relationships: [`);
      for (const f of relFks) {
        out.push(`${ind(5)}{`);
        out.push(`${ind(6)}foreignKeyName: "${f.conname}";`);
        out.push(`${ind(6)}columns: [${f.cols.map((c) => `"${c}"`).join(', ')}];`);
        out.push(`${ind(6)}isOneToOne: false;`);
        out.push(`${ind(6)}referencedRelation: "${f.ref}";`);
        out.push(`${ind(6)}referencedColumns: [${f.ref_cols.map((c) => `"${c}"`).join(', ')}];`);
        out.push(`${ind(5)}},`);
      }
      out.push(`${ind(4)}];`);
    }
    out.push(`${ind(3)}};`);
  }
  out.push(`${ind(2)}};`);
}

relationBlock('r');
relationBlock('v');

out.push(`${ind(2)}Functions: {`);
for (const f of functions) {
  const names = f.proargnames ?? [];
  const modes = f.proargmodes ?? names.map(() => 'i');
  const allTypes = f.proallargtypes ?? f.argtypes;
  const inputs = [];
  const tableCols = [];
  names.forEach((name, i) => {
    const mode = modes[i] ?? 'i';
    if (mode === 'i' || mode === 'b' || mode === 'v') inputs.push({ name, type: allTypes[i] });
    if (mode === 't' || mode === 'o') tableCols.push({ name, type: allTypes[i] });
  });
  const firstOptional = f.pronargs - f.pronargdefaults;
  out.push(`${ind(3)}${f.proname}: {`);
  if (inputs.length === 0) {
    out.push(`${ind(4)}Args: never;`);
  } else {
    out.push(`${ind(4)}Args: {`);
    inputs.forEach((a, i) => out.push(`${ind(5)}${a.name}${i >= firstOptional ? '?' : ''}: ${tsType(a.type)};`));
    out.push(`${ind(4)}};`);
  }
  let ret;
  if (tableCols.length) {
    ret = `{ ${tableCols.map((c) => `${c.name}: ${tsType(c.type)}`).join('; ')} }[]`;
  } else {
    ret = tsType(f.prorettype) + (f.proretset ? '[]' : '');
  }
  out.push(`${ind(4)}Returns: ${ret};`);
  out.push(`${ind(3)}};`);
}
out.push(`${ind(2)}};`);

out.push(`${ind(2)}Enums: {`);
for (const e of enums) out.push(`${ind(3)}${e.typname}: ${e.labels.map((l) => `"${l}"`).join(' | ')};`);
out.push(`${ind(2)}};`);
out.push(`${ind(2)}CompositeTypes: { [_ in never]: never };`);
out.push(`${ind(1)}};`);
out.push('};');
out.push('');
out.push(`type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`);

const target = join(root, 'src', 'types', 'database.ts');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
process.exit(0);
